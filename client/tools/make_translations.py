def esc(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def write(lang: str, index: int) -> None:
    lines = ['msgid ""', 'msgstr ""', '"Content-Type: text/plain; charset=UTF-8\\n"', f'"Language: {lang}\\n"', ""]
    for key, values in T.items():
        lines += [f'msgid "{key}"', f'msgstr "{esc(values[index])}"', ""]
    (OUT / f"{lang}.po").write_text("\n".join(lines), encoding="utf-8", newline="\n")


